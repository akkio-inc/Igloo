// TestDuckDBKeywords checks keywords.go against duckdb_keywords() of the
// DuckDB Igloo links, whose categories decide which names the translation
// quotes (see quoteKeywordNames). Run with -update to write it again after
// DuckDB changes, and review the diff.
func TestDuckDBKeywords(t *testing.T) {
	conn := session(t)
	rows, err := conn.QueryContext(context.Background(), "SELECT keyword_category, keyword_name FROM duckdb_keywords() ORDER BY 1, 2")
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	byCategory := map[string][]string{}
	for rows.Next() {
		var category, name string
		if err := rows.Scan(&category, &name); err != nil {
			t.Fatal(err)
		}
		byCategory[category] = append(byCategory[category], name)
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	var b strings.Builder
	b.WriteString("// Code generated by go test -run TestDuckDBKeywords -update; DO NOT EDIT.\n\npackage snowflake\n\n")
	b.WriteString("// duckdbKeywordList is duckdb_keywords() of the DuckDB Igloo links: the\n")
	b.WriteString("// keywords of each category, separated by spaces (see duckdbKeywords).\n")
	b.WriteString("var duckdbKeywordList = map[string]string{\n")
	categories := make([]string, 0, len(byCategory))
	for c := range byCategory {
		categories = append(categories, c)
	}
	slices.Sort(categories)
	for _, c := range categories {
		b.WriteString("\t" + `"` + c + `": ""`)
		line := ""
		for _, w := range byCategory[c] {
			if len(line)+len(w) > 90 {
				b.WriteString(" +\n\t\t\"" + line + "\"")
				line = ""
			}
			line += w + " "
		}
		b.WriteString(" +\n\t\t\"" + strings.TrimSuffix(line, " ") + "\",\n")
	}
	b.WriteString("}\n")
	src, err := gofmt.Source([]byte(b.String()))
	if err != nil {
		t.Fatalf("%v\n%s", err, b.String())
	}
	if *update {
		if err := os.WriteFile("keywords.go", src, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile("keywords.go")
	if err != nil {
		t.Fatal(err)
	}
	if string(have) != string(src) {
		t.Errorf("keywords.go differs from duckdb_keywords(); run go test -run TestDuckDBKeywords -update and review the diff\n%s", src)
	}
}

// TestKeywordNames runs statements whose tables, CTEs and select items are
// named with words DuckDB keeps as keywords, which Snowflake reads as names
// there (see quoteKeywordNames). The first is an audience report's join of
// its CTEs, which failed with "syntax error at or near CROSS": DuckDB read
// the alias AT as the start of AT (VERSION => ...). SEMI, ANTI and
// POSITIONAL would start DuckDB's joins of those kinds, GLOB and SIMILAR its
// operators, NOTNULL after an expression its IS NOT NULL.
func TestKeywordNames(t *testing.T) {
	conn := session(t)
	report := `with category_metrics as (select 'news' as category, 2 as people union all select 'sport', 3),
		audience_total as (select 5 as total_people), totals as (select 10 as n)
		select %s from category_metrics cm cross join audience_total at cross join totals t order by 1`
	for _, c := range []runCase{
		{sql: fmt.Sprintf(report, "cm.category, cm.people / at.total_people as share, t.n"), want: []string{"news|0.4|10", "sport|0.6|10"},
			cols: []string{"CATEGORY", "SHARE", "N"}},
		{sql: fmt.Sprintf(report, "category, people / total_people, n"), want: []string{"news|0.4|10", "sport|0.6|10"}},
		{sql: `select at.a, semi.a, anti.a, positional.a, glob.a, similar.a, freeze.a from (select 1 a) at, (select 1 a) semi
			join (select 1 a) anti on anti.a = semi.a cross join (select 1 a) positional left join (select 1 a) glob on true,
			(select 1 a) as similar natural join (select 1 a) freeze`, want: []string{"1|1|1|1|1|1|1"}},
		{sql: `select count(*) from (select 1 a) at where a = 1`, want: []string{"1"}},
		{sql: `select at.a from (select 1 a) as at(a), lateral flatten(input => [1]) semi where semi.value = 1`, want: []string{"1"}},
		// A CTE named so, with and without a column list.
		{sql: `with at as (select 1 a), semi (b) as (select 2) select at.a + semi.b from at, semi`, want: []string{"3"}},
		// Select items' aliases without AS, in a subquery, a CTE and a set
		// operation's second select; at the top they name the result in
		// upper case, as Snowflake does. Each is the name it was: ORDER BY
		// an expression of one reads the item it names, not the column.
		{sql: `select * from (select 1 year, 2 at, 3 semi, 4 value, a notnull from (select null a))`, want: []string{"1|2|3|4|NULL"},
			cols: []string{"YEAR", "AT", "SEMI", "VALUE", "NOTNULL"}},
		{sql: `with c as (select 1 year, 2 at) select c.year, c.at from c union all select 3 year, 4 at`, want: []string{"1|2", "3|4"},
			cols: []string{"YEAR", "AT"}},
		{sql: `select 1 year, 2 at, null notnull`, want: []string{"1|2|NULL"}, cols: []string{"YEAR", "AT", "NOTNULL"}},
		{sql: `select x year from (select 1 x, 5 year union all select 2, 4) order by year + 0`, want: []string{"1", "2"}},
		// AT, ASOF and SEMI where Snowflake and DuckDB read them as clauses.
		{sql: `select t.x, q.px from (values (1, 10), (2, 20)) t(x, ts) asof join (values (8, 'a'), (15, 'b')) q(ts, px)
			match_condition (t.ts >= q.ts) order by 1`, want: []string{"1|a", "2|b"}},
	} {
		run(t, conn, c)
	}

	// Tables named so in UPDATE, DELETE and MERGE, and select items'
	// aliases in CREATE TABLE ... AS, which keeps them as written.
	ctx := context.Background()
	for _, s := range []string{
		`create table k as select 1 year, 2 at, 3 x`,
		`update k at set x = at.x + 1 where at.year = 1`,
		`merge into k at using (select 1 year) semi on at.year = semi.year when matched then update set x = at.x * 10`,
		`delete from k at where at.x = 0`,
	} {
		res, err := Translate(s, Options{})
		if err != nil {
			t.Fatalf("%s: %v", s, err)
		}
		if _, err := conn.ExecContext(ctx, res.SQL); err != nil {
			t.Fatalf("%s\nDuckDB: %s\n%v", s, res.SQL, err)
		}
	}
	if got := rowsOf(t, conn, `SELECT string_agg(column_name, ',' ORDER BY ordinal_position) FROM information_schema.columns WHERE table_name = 'k'`); got != "year,at,x" {
		t.Errorf("CREATE TABLE ... AS names k's columns %s, want year,at,x", got)
	}
	if got := rowsOf(t, conn, `SELECT x FROM k`); got != "40" {
		t.Errorf("after UPDATE and MERGE, x is %s, want 40", got)
	}

	// Every keyword of the DuckDB Igloo links: as a table's alias after AS,
	// as one without AS where Snowflake reads an alias there, and as a
	// select item's alias without AS, where it does too.
	for word := range duckdbKeywords {
		forms := []string{"select %[1]s.a from (select 1 as a) as %[1]s"}
		if word != "as" && aliasAfterTable(&node{kind: kWord, tok: token{kind: kWord, text: word}}, nil) {
			forms = append(forms, "select %[1]s.a, a from (select 1 as a) %[1]s where a = 1")
		}
		if up := strings.ToUpper(word); !selectEnd[up] && !expressionEndWords[up] {
			forms = append(forms, "select * from (select 1 %[1]s, 2 b) where b = 2")
		}
		for _, f := range forms {
			q := fmt.Sprintf(f, word)
			res, err := Translate(q, Options{})
			if err != nil {
				t.Errorf("%s: %v", q, err)
				continue
			}
			rows, err := conn.QueryContext(ctx, res.SQL)
			if err != nil {
				t.Errorf("%s\nDuckDB: %s\n%v", q, res.SQL, err)
				continue
			}
			names, _ := rows.Columns()
			rows.Close()
			if strings.HasPrefix(f, "select * ") && names[0] != word {
				t.Errorf("%s names its column %q", q, names[0])
			}
		}
	}
}
